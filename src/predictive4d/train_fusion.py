"""Offline learned pose fusion with independently measured pose GT.

Each candidate file is generated by a frozen SLAM run without reading GT.
Training and validation must use disjoint *sequences*, not shuffled frames.
"""
from __future__ import annotations
from pathlib import Path
import json
import numpy as np
import torch
from scipy.spatial.transform import Rotation
from .data import read_gt
from .geometry import invert, se3_log
from .fusion_head import (FEATURE_NAMES, ReliabilityFusionHead,
                          fuse_torch, fuse_numpy)


def load_pairs(pairs, tolerance=.02, require_good_geometry=True, geometry_source="joint"):
    """Pairs of (fusion_candidates.npz, groundtruth.txt); T_wc GT is anchored at frame0."""
    feats, pred, geo, truth, groups = [], [], [], [], []
    for packet_path, gt_path in pairs:
        packet_path, gt_path = Path(packet_path).resolve(), Path(gt_path).resolve()
        with np.load(packet_path, allow_pickle=False) as d:
            if geometry_source not in ('joint','independent'):
                raise ValueError('geometry_source must be joint or independent')
            postfix='' if geometry_source=='joint' else '_independent'
            f, p, g = d['features'+postfix].copy(), d['T_pred'].copy(), d['T_geo'+postfix].copy()
            ts, valid = d['timestamps'].copy(), d['valid_geo'+postfix].copy().astype(bool)
            t_origin = float(d['origin_timestamp'])
        if f.ndim != 2 or f.shape[1] != len(FEATURE_NAMES) or p.shape != g.shape or p.shape != (len(f),4,4):
            raise ValueError(f'Invalid fusion sample schema: {packet_path}')
        reference = read_gt(gt_path)
        if not reference:
            raise ValueError(f'No trajectory GT: {gt_path}')
        gt_ts = np.asarray([t for t, _ in reference])
        oi = int(np.argmin(abs(gt_ts-t_origin)))
        if abs(gt_ts[oi]-t_origin) > tolerance:
            raise ValueError(f'No GT near first SLAM frame {t_origin} for {packet_path}')
        gt_origin = reference[oi][1]  # GT T_wc0 ; world frame of first SLAM camera
        count = 0
        for idx,t in enumerate(ts):
            if require_good_geometry and not valid[idx]:
                continue
            k = int(np.argmin(abs(gt_ts-t)))
            if abs(gt_ts[k]-t) > tolerance:
                continue
            t_gt = invert(reference[k][1]) @ gt_origin
            if not np.isfinite(f[idx]).all() or not all(np.isfinite(x).all() for x in (p[idx],g[idx],t_gt)):
                continue
            feats.append(f[idx]);pred.append(p[idx]);geo.append(g[idx]);truth.append(t_gt)
            groups.append(str(packet_path)); count += 1
        if not count:
            raise RuntimeError(f'No usable GT-aligned fusion samples in {packet_path}')
    return dict(features=np.stack(feats).astype(np.float32),
                pred=np.stack(pred), geo=np.stack(geo), gt=np.stack(truth), groups=groups)


def tensors(data, device='cpu'):
    pred=data['pred'];geo=data['geo']
    rel=np.stack([se3_log(g @ invert(p)) for g,p in zip(geo,pred)])
    return (torch.tensor(data['features'], dtype=torch.float32, device=device),
            torch.tensor(pred, dtype=torch.float32, device=device),
            torch.tensor(rel, dtype=torch.float32, device=device),
            torch.tensor(data['gt'], dtype=torch.float32, device=device))


def pose_losses(fused, gt, rotation_weight=0.35):
    """Per-sample metric loss; camera center error + rotation chordal angle proxy."""
    r, t = fused[..., :3, :3], fused[..., :3, 3]
    rg, tg = gt[..., :3, :3], gt[..., :3, 3]
    center = -(r.transpose(-2,-1) @ t[...,None]).squeeze(-1)
    center_gt = -(rg.transpose(-2,-1) @ tg[...,None]).squeeze(-1)
    position_error = torch.linalg.vector_norm(center-center_gt,dim=-1)
    rotation_error = torch.linalg.matrix_norm(r-rg,ord='fro',dim=(-2,-1)) / np.sqrt(2.)
    return position_error + float(rotation_weight)*rotation_error


def report(data, head, mean, std, tuned_fixed_weight=None):
    x=(data['features']-mean)/np.maximum(std,1e-4)
    x=np.clip(x,-8.,8.)
    with torch.inference_mode():
        w=head(torch.tensor(x,dtype=torch.float32)).cpu().numpy()
    tests={'neural_only':np.zeros_like(w), 'geometry_only':np.ones_like(w),
           'fixed_half':np.full_like(w,.5), 'learned':w}
    if tuned_fixed_weight is not None:
        tests['validation_tuned_fixed']=np.full_like(w,float(tuned_fixed_weight))
    out={}
    for name, weights in tests.items():
        pose=np.stack([fuse_numpy(p,g,float(a)) for p,g,a in zip(data['pred'],data['geo'],weights)])
        estimated_centers=-np.einsum('nij,nj->ni',pose[:,:3,:3].transpose(0,2,1),pose[:,:3,3])
        gt=data['gt'];true_centers=-np.einsum('nij,nj->ni',gt[:,:3,:3].transpose(0,2,1),gt[:,:3,3])
        translation=np.linalg.norm(estimated_centers-true_centers,axis=1)
        rr=np.einsum('nij,njk->nik',gt[:,:3,:3].transpose(0,2,1),pose[:,:3,:3])
        rotation=np.rad2deg(Rotation.from_matrix(rr).magnitude())
        out[name]={'translation_rmse_m':float(np.sqrt(np.mean(translation**2))),
                   'translation_mean_m':float(translation.mean()),
                   'rotation_mean_deg':float(rotation.mean()),
                   'mean_geometry_weight':float(np.mean(weights))}
    return out


def train_fusion(train_pairs,val_pairs,out,epochs=150,lr=1e-3,seed=42,geometry_source="joint"):
    train_roots={str(Path(p).resolve()) for p,_ in train_pairs}
    val_roots={str(Path(p).resolve()) for p,_ in val_pairs}
    if train_roots & val_roots:raise ValueError('Train and validation sequences overlap')
    if not train_pairs or not val_pairs:raise ValueError('Need disjoint train and validation sequences')
    torch.manual_seed(int(seed)); np.random.seed(int(seed))
    tr=load_pairs(train_pairs,geometry_source=geometry_source);va=load_pairs(val_pairs,geometry_source=geometry_source)
    mean=tr['features'].mean(0).astype(np.float32)
    std=tr['features'].std(0).astype(np.float32);std=np.maximum(std,1e-4)
    tr['features']=np.clip((tr['features']-mean)/std,-8.,8.)
    va['features']=np.clip((va['features']-mean)/std,-8.,8.)
    x,p,rel,gt=tensors(tr);xv,pv,rv,gv=tensors(va)
    head=ReliabilityFusionHead();optimizer=torch.optim.AdamW(head.parameters(),lr=lr,weight_decay=1e-3)
    best=float('inf');best_state=None;patience=0
    for epoch in range(int(epochs)):
        head.train();optimizer.zero_grad(set_to_none=True)
        w=head(x);loss=pose_losses(fuse_torch(p,rel,w),gt).mean()
        loss.backward();torch.nn.utils.clip_grad_norm_(head.parameters(),1.)
        optimizer.step();head.eval()
        with torch.no_grad():
            vloss=float(pose_losses(fuse_torch(pv,rv,head(xv)),gv).mean())
        if vloss < best-1e-7:
            best=vloss;best_state={k:v.detach().cpu().clone() for k,v in head.state_dict().items()};patience=0
        else:
            patience+=1
        if patience>=25:break
    head.load_state_dict(best_state);head.eval()
    # Select a strong fixed baseline using *only* validation samples.
    with torch.no_grad():
        fixed_losses=[(float(pose_losses(fuse_torch(pv,rv,torch.full((len(pv),),i/20.)),gv).mean()),i/20.)
                      for i in range(21)]
    tuned_w=min(fixed_losses)[1]
    out=Path(out);out.parent.mkdir(parents=True,exist_ok=True)
    torch.save(dict(arch='ReliabilityFusionHead-v1', trained=True,
                    feature_names=FEATURE_NAMES,feature_mean=mean.tolist(),feature_std=std.tolist(),
                    model=head.state_dict(),tuned_fixed_weight=tuned_w,
                    geometry_source=geometry_source,
                    train_sequences=sorted(train_roots),validation_sequences=sorted(val_roots)),out)
    # Return normalized evaluation by restoring raw features for reporting.
    for dat in (tr,va): dat['features']=dat['features']*std+mean
    results={'train_samples':len(tr['features']),'validation_samples':len(va['features']),
             'best_validation_loss':best,'tuned_fixed_weight':tuned_w,
             'validation':report(va,head,mean,std,tuned_w)}
    out.with_suffix('.json').write_text(json.dumps(results,indent=2),encoding='utf8')
    return results


def evaluate_fusion(checkpoint,pairs):
    obj=torch.load(str(checkpoint),map_location='cpu',weights_only=True)
    if obj.get('arch')!='ReliabilityFusionHead-v1':raise ValueError('Wrong fusion checkpoint type')
    data=load_pairs(pairs,geometry_source=obj.get('geometry_source','joint'))
    used={str(Path(p).resolve()) for p,_ in pairs}
    trained=set(obj.get('train_sequences',[])) | set(obj.get('validation_sequences',[]))
    if used & trained:raise ValueError('Refusing to evaluate on training/validation candidate files')
    head=ReliabilityFusionHead();head.load_state_dict(obj['model']);head.eval()
    summary=report(data,head,np.asarray(obj['feature_mean']),np.asarray(obj['feature_std']),obj['tuned_fixed_weight'])
    return {'samples':len(data['features']), 'metrics':summary}
